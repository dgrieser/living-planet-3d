/**
 * Crops the national height-reference grids to the hero areas, so the runtime gets ellipsoidal heights
 * within a centimetre of the national models there (docs/earth-sim/02 §8, 03 §0, 04 §0). Writes the grid
 * layout as a tiny generated module (src/sims/earth/data/heroGeoids.js – bundled) and the values as
 * public/earth/hero-geoids.json (loaded with the global geoid):
 *
 *   node tools/earth-pipeline/build-hero-geoids.mjs <de_bkg_gcg2016.tif> <dk_sdfi_dvr90_2023.tif>
 *
 *  - Lübbecke: GCG2016 quasigeoid (BKG, CC BY 4.0) – height anomaly ζ for DHHN2016 normal heights;
 *  - Fanø: DVR90(2023) geoid (Klimadatastyrelsen, CC BY 4.0).
 * Both from the PROJ data CDN (https://cdn.proj.org). Mapterhorn carries the national heights in these
 * areas (checked against NRW's DGM1: mean difference 0.001 m), so h = H + ζ/N exactly as the agencies do.
 * Grids are pixel-is-point; the crop keeps whole nodes and a margin around each hero box.
 */
import fs from 'node:fs';
import { fromArrayBuffer } from 'geotiff';

const HERO_FILE = 'earth/hero-geoids.json';

const [gcg, dvr, out = 'src/sims/earth/data/heroGeoids.js', valuesOut = 'public/earth/hero-geoids.json'] = process.argv.slice(2);
if (!gcg || !dvr) {
  console.error('usage: node tools/earth-pipeline/build-hero-geoids.mjs <de_bkg_gcg2016.tif> <dk_sdfi_dvr90_2023.tif> [out.js]');
  process.exit(1);
}

// hero boxes of places.js plus a 0.15° margin (the blend to EGM2008 happens around the box edge)
const CROPS = [
  { id: 'luebbecke', file: gcg, model: 'GCG2016 (BKG)', south: 52.05, north: 52.55, west: 8.25, east: 9.0 },
  { id: 'fanoe', file: dvr, model: 'DVR90(2023) (Klimadatastyrelsen)', south: 55.1, north: 55.75, west: 8.0, east: 8.8 },
];

const grids = [];
for (const crop of CROPS) {
  const buf = fs.readFileSync(crop.file);
  const tiff = await fromArrayBuffer(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  const image = await tiff.getImage();
  const [lon0, lat0] = image.getOrigin(); // first node (pixel-is-point)
  const [dLon, dLatNeg] = image.getResolution();
  const dLat = -dLatNeg;
  const width = image.getWidth();
  const [raster] = await image.readRasters();
  const c0 = Math.floor((crop.west - lon0) / dLon);
  const c1 = Math.ceil((crop.east - lon0) / dLon);
  const r0 = Math.floor((lat0 - crop.north) / dLat); // north row
  const r1 = Math.ceil((lat0 - crop.south) / dLat);
  const cols = c1 - c0 + 1;
  const rows = r1 - r0 + 1;
  const values = [];
  // south row first, like geodesy.js createGeoidGrid
  for (let r = r1; r >= r0; r--) {
    for (let c = c0; c <= c1; c++) {
      const v = raster[r * width + c];
      if (!Number.isFinite(v) || v < -1000) throw new Error(`${crop.id}: no data at row ${r}, col ${c}`);
      values.push(Math.round(v * 10000) / 10000);
    }
  }
  grids.push({
    id: crop.id, model: crop.model,
    lat0: +(lat0 - r1 * dLat).toFixed(9), lon0: +(lon0 + c0 * dLon).toFixed(9),
    dLat: +dLat.toFixed(12), dLon: +dLon.toFixed(12), rows, cols, values,
  });
  console.log(`${crop.id}: ${rows} × ${cols} nodes from ${crop.model}`);
}

const layout = grids.map(({ values, ...rest }) => ({ ...rest, count: values.length }));
const body = `// Generated by tools/earth-pipeline/build-hero-geoids.mjs – do not edit.
// Layout of the national height references cropped to the hero areas (south row first); the values (m)
// are in public/${HERO_FILE}. GCG2016 © BKG (2023) CC BY 4.0; DVR90(2023) © Klimadatastyrelsen CC BY 4.0;
// via the PROJ data CDN.
export const HERO_GEOIDS_FILE = '${HERO_FILE}';
export const HERO_GEOIDS = Object.freeze(${JSON.stringify(layout)});
`;
fs.writeFileSync(out, body);
const values = JSON.stringify(Object.fromEntries(grids.map((g) => [g.id, g.values])));
fs.writeFileSync(valuesOut, values);
console.log(`wrote ${out} (${body.length} bytes) and ${valuesOut} (${values.length} bytes)`);
